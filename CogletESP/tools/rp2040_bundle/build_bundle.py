#!/usr/bin/env python3
"""Package the RP2040 program (CogletESP/RP2040/*.py) for automatic updates.

--cc   writes a C++ source with every file, its CRC-32 and the bundle id; the
       ESP firmware compiles it in and sends the files to the RP2040 whenever
       the RP2040 reports a different bundle id (see main/coglet_rp2040_sync.h).
       Runs from main/CMakeLists.txt on every build; the file is only rewritten
       when the RP2040 files changed.
--site writes the files plus manifest.json for the web flasher's first-time
       RP2040 setup.

The bundle id is a hash of all file names and contents, so any change to any
RP2040 file produces a new id and triggers an update.
"""
import argparse
import hashlib
import json
import os
import shutil
import sys
import zlib

INCLUDE_EXT = (".py",)


def collect(src):
    files = []
    for name in sorted(os.listdir(src)):
        path = os.path.join(src, name)
        if os.path.isfile(path) and name.endswith(INCLUDE_EXT) and not name.startswith("."):
            with open(path, "rb") as f:
                files.append((name, f.read()))
    if not any(n == "main.py" for n, _ in files) or not any(n == "coglet_updater.py" for n, _ in files):
        sys.exit("RP2040 folder must contain main.py and coglet_updater.py")
    h = hashlib.sha1()
    for name, data in files:
        h.update(name.encode() + b"\0" + data + b"\0")
    return h.hexdigest()[:12], files


def c_bytes(data, width=64):
    lines = []
    for i in range(0, len(data), width):
        lines.append('    "' + "".join("\\x{:02x}".format(b) for b in data[i:i + width]) + '"')
    return "\n".join(lines) if lines else '    ""'


def write_cc(path, bundle_id, files):
    out = [
        "// GENERATED by tools/rp2040_bundle/build_bundle.py from CogletESP/RP2040.",
        "// Do not edit and do not commit: it is rebuilt on every build.",
        '#include "coglet_rp2040_sync.h"',
        "",
        "namespace {",
    ]
    for i, (name, data) in enumerate(files):
        out.append("const char kFile{}[] =\n{};".format(i, c_bytes(data)))
    out.append("const CogletRp2040::BundleFile kFiles[] = {")
    # main.py and the updater go last: if anything is interrupted, the old
    # launcher keeps working and the next boot repeats the update.
    order = sorted(range(len(files)), key=lambda i: files[i][0] in ("main.py", "coglet_updater.py"))
    for i in order:
        name, data = files[i]
        out.append('    {{"{}", reinterpret_cast<const uint8_t*>(kFile{}), {}, 0x{:08x}u}},'.format(
            name, i, len(data), zlib.crc32(data) & 0xFFFFFFFF))
    out.append("};")
    out.append("}  // namespace")
    out.append("")
    out.append("namespace CogletRp2040 {")
    out.append('const char* const kBundleId = "{}";'.format(bundle_id))
    out.append("const BundleFile* const kBundleFiles = kFiles;")
    out.append("const size_t kBundleFileCount = sizeof(kFiles) / sizeof(kFiles[0]);")
    out.append("}  // namespace CogletRp2040")
    data = "\n".join(out) + "\n"
    if os.path.isfile(path):
        with open(path, encoding="utf-8") as f:
            if f.read() == data:
                return False
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(data)
    return True


def write_site(site, bundle_id, files):
    os.makedirs(site, exist_ok=True)
    manifest = {"bundle_id": bundle_id, "files": []}
    for name, data in files:
        with open(os.path.join(site, name), "wb") as f:
            f.write(data)
        manifest["files"].append({"name": name, "size": len(data),
                                  "md5": hashlib.md5(data).hexdigest()})
    with open(os.path.join(site, "manifest.json"), "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=2)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", required=True, help="CogletESP/RP2040")
    ap.add_argument("--cc", help="generated C++ source to write")
    ap.add_argument("--site", help="folder for the web flasher")
    args = ap.parse_args(argv)
    bundle_id, files = collect(args.src)
    total = sum(len(d) for _, d in files)
    if args.cc:
        changed = write_cc(args.cc, bundle_id, files)
        print("[rp2040-bundle] {} files, {} KB, id {}{}".format(
            len(files), total // 1024, bundle_id, "" if changed else " (unchanged)"))
    if args.site:
        write_site(args.site, bundle_id, files)
        print("[rp2040-bundle] site files written to", args.site)
    return 0


if __name__ == "__main__":
    sys.exit(main())
