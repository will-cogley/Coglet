"""Write the Christmas sounds (out/approved/*.ogg) as firmware headers.

python3 export_xmas_headers.py <path/to/CogletESP/main/coglet_sounds>
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "out", "approved")

SOUNDS = [
    ("xmas_lyrical.ogg", "coglet_dance_lyrical.h", "CogletDanceLyrical",
     "Coglet Christmas dance (lyrical) - Silent Night (Gruber, 1818, public domain),\n"
     "// our own arrangement: piano, strings, celesta. 104 BPM 3/4, ~31 s."),
    ("xmas_classic.ogg", "coglet_dance_classic.h", "CogletDanceClassic",
     "Coglet Christmas dance (classic) - Jingle Bells (Pierpont, 1857, public domain),\n"
     "// our own arrangement: sleigh bells, stride piano, bass, glockenspiel. 136 BPM, ~32 s."),
    ("xmas_grand.ogg", "coglet_dance_grand.h", "CogletDanceGrand",
     "Coglet Christmas dance (grand) - Joy to the World (Antioch, 1839, public domain),\n"
     "// our own arrangement: organ, brass, choir, timpani. 84 BPM 2/4, ~32 s."),
    ("xmas_startup.ogg", "coglet_christmas_boot_chime.h", "CogletChristmasBootChime",
     "Coglet Christmas startup sound - sleigh bells and the first 'jingle bells', ~3.3 s."),
    ("xmas_reminder.ogg", "coglet_christmas_reminder_chime.h", "CogletChristmasReminderChime",
     "Coglet Christmas reminder sound - church-bell 'ding-dong' over sleigh bells, ~2.7 s."),
]


def main(dst, sounds=SOUNDS, prefix="xmas"):
    for src, header, ns, title in sounds:
        data = open(os.path.join(SRC, src), "rb").read()
        rows = []
        for i in range(0, len(data), 12):
            rows.append("    " + " ".join("0x{:02X},".format(b) for b in data[i:i + 12]))
        text = (
            "// {title}\n"
            "// Embedded Ogg/Opus, mono, 24 kHz, 60 ms frames. Generated by dj/export_{prefix}_headers.py\n"
            "// from dj/{prefix}.py; the RP2040 choreography (RP2040/dance_{prefix}.py) uses the same score.\n"
            "// Use directly with AudioService::PlaySound().\n"
            "#pragma once\n\n"
            "#include <cstdint>\n"
            "#include <string_view>\n\n"
            "namespace {ns} {{\n"
            "static constexpr uint8_t kOgg[] = {{\n"
            "{rows}\n"
            "}};\n\n"
            "inline std::string_view Ogg() {{\n"
            "    return std::string_view(reinterpret_cast<const char*>(kOgg), sizeof(kOgg));\n"
            "}}\n"
            "}}  // namespace {ns}\n"
        ).format(title=title, ns=ns, rows="\n".join(rows), prefix=prefix)
        with open(os.path.join(dst, header), "w") as f:
            f.write(text)
        print("{:<36} {:>6} bytes".format(header, len(data)))


if __name__ == "__main__":
    main(sys.argv[1])
